export function gpaToTarazRange(gpa, field) {
  if (field && !["tajrobi", "riazi", "ensani"].includes(field)) return null
  if (gpa < 10 || gpa > 20) return null
  if (gpa < 15) {
    const band = GPA_TARAZ_BANDS.find(([low, high]) => low <= gpa && gpa < high)
    return band ? [band[2], band[3]] : null
  }
  for (let index = 0; index < GPA_TARAZ_DATA.length; index += 1) {
    const [gpa1, low1, high1] = GPA_TARAZ_DATA[index]
    if (Math.abs(gpa - gpa1) < 1e-9) return [low1, high1]
    if (index + 1 < GPA_TARAZ_DATA.length) {
      const [gpa2, low2, high2] = GPA_TARAZ_DATA[index + 1]
      if (gpa1 < gpa && gpa < gpa2) {
        const ratio = (gpa - gpa1) / (gpa2 - gpa1)
        return [Math.round(low1 + ratio * (low2 - low1)), Math.round(high1 + ratio * (high2 - high1))]
      }
    }
  }
  return null
}

export function percentToTaraz(average, field = "tajrobi") {
  const data = PERCENT_TARAZ_DATA_1404[field]
  if (!data || average < -33 || average > 100) return null
  if (average < 0) return 3500
  for (let index = 0; index < data.length; index += 1) {
    const [percent1, taraz1] = data[index]
    if (Math.abs(average - percent1) < 1e-9) return taraz1
    if (index + 1 < data.length) {
      const [percent2, taraz2] = data[index + 1]
      if (percent1 < average && average < percent2) {
        const ratio = (average - percent1) / (percent2 - percent1)
        return Math.round(taraz1 + ratio * (taraz2 - taraz1))
      }
    }
  }
  return null
}

export function calcWeightedGpa(scores, field) {
  let total = 0
  let coefficientTotal = 0
  for (const subject of GPA_COEF[field] || []) {
    const value = scores[subject.id]
    if (value !== undefined && value >= 10 && value <= 20) {
      total += value * subject.coef
      coefficientTotal += subject.coef
    }
  }
  return coefficientTotal ? total / coefficientTotal : null
}

export function calcWeightedPercent(scores, field) {
  const subjects = PCT_SUBJECTS[field] || []
  if (!subjects.length) return null
  let total = 0
  let coefficientTotal = 0
  for (const subject of subjects) {
    const value = scores[subject.id]
    if (value === undefined || value < -33 || value > 100) return null
    total += value * subject.coef
    coefficientTotal += subject.coef
  }
  return coefficientTotal ? total / coefficientTotal : null
}

export function getStatus(rank) {
  if (!rank) return "—"
  if (rank.includes("زیر")) return "عالی 🔥"
  const numbers = rank.replaceAll("–", "-").split("-").map(part => Number(part.replace(/[^0-9۰-۹]/g, "").replace(/[۰-۹]/g, digit => "۰۱۲۳۴۵۶۷۸۹".indexOf(digit)))).filter(Number.isFinite)
  if (!numbers.length) return "—"
  const average = numbers.reduce((sum, number) => sum + number, 0) / numbers.length
  if (average < 500) return "عالی 🔥"
  if (average < 1500) return "خیلی خوب ⭐"
  if (average < 5000) return "خوب"
  if (average < 15000) return "متوسط"
  return "نیاز به تلاش"
}

